// Command genstylematrix generates the renderer-scoped Style-field conversion
// table from the validated evidence matrix. Generated code is deterministic and
// has no runtime XML IO.
//
// This generator is separate from genmatrix. Style fields have no arity, no
// prefix dispatch and no paren form, so they cannot use the tag schema. The
// validation below therefore checks conversion evidence, not signatures.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/xml"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
)

type conv struct {
	Renderer string `xml:"renderer,attr"`
	Parse    string `xml:"parse,attr"`
	Post     string `xml:"post,attr"`
	Verified string `xml:"verified,attr"`
	Cite     string `xml:"cite,attr"`
}

type field struct {
	Name  string `xml:"name,attr"`
	Kind  string `xml:"kind,attr"`
	Convs []conv `xml:"conv"`
}

type matrix struct {
	Fields []field `xml:"stylefield"`
	Meta   struct {
		Parses []struct {
			ID string `xml:"id,attr"`
		} `xml:"parses>parse"`
		Posts []struct {
			ID string `xml:"id,attr"`
		} `xml:"posts>post"`
	} `xml:"meta"`
}

// rendererOrder is the canonical bit order shared with the tag matrix.
var rendererOrder = []string{"libass", "xy", "vsm"}

// canonicalNewlines gives a stable evidence digest across Git worktrees with
// LF, CRLF or CR physical line endings.
func canonicalNewlines(data []byte) []byte {
	data = bytes.ReplaceAll(data, []byte("\r\n"), []byte("\n"))
	return bytes.ReplaceAll(data, []byte("\r"), []byte("\n"))
}

func run() error {
	check := flag.Bool("check", false, "fail if generated output is stale")
	flag.Parse()
	input := filepath.Join("..", "..", "..", "docs", "ass-style-fields.xml")
	data, err := os.ReadFile(input)
	if err != nil {
		return err
	}
	var m matrix
	if err = xml.Unmarshal(data, &m); err != nil {
		return err
	}
	if len(m.Fields) == 0 {
		return fmt.Errorf("%s declares no stylefield rows", input)
	}

	parses := make(map[string]bool)
	for _, p := range m.Meta.Parses {
		if p.ID == "" || parses[p.ID] {
			return fmt.Errorf("duplicate or unnamed parse token %q", p.ID)
		}
		parses[p.ID] = true
	}
	posts := make(map[string]bool)
	for _, p := range m.Meta.Posts {
		if p.ID == "" || posts[p.ID] {
			return fmt.Errorf("duplicate or unnamed post token %q", p.ID)
		}
		posts[p.ID] = true
	}

	sort.Slice(m.Fields, func(i, j int) bool { return m.Fields[i].Name < m.Fields[j].Name })
	sum := sha256.Sum256(canonicalNewlines(data))
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(&out, "package renderer")
	fmt.Fprintf(&out, "const styleMatrixSHA256 = %q\n", fmt.Sprintf("%x", sum))
	fmt.Fprintln(&out, "var styleFieldMatrix = map[string]styleFieldEvidence{")
	seen := make(map[string]bool)
	for _, f := range m.Fields {
		if f.Name == "" || seen[f.Name] {
			return fmt.Errorf("duplicate or unnamed stylefield %q", f.Name)
		}
		seen[f.Name] = true
		if len(f.Convs) != len(rendererOrder) {
			return fmt.Errorf("stylefield %s: need one conv per renderer, got %d", f.Name, len(f.Convs))
		}
		// The generator must not silently accept a short or reordered row.
		byRenderer := make(map[string]conv)
		for _, c := range f.Convs {
			if _, ok := byRenderer[c.Renderer]; ok {
				return fmt.Errorf("stylefield %s: duplicate conv for %q", f.Name, c.Renderer)
			}
			byRenderer[c.Renderer] = c
		}
		for _, name := range rendererOrder {
			if _, ok := byRenderer[name]; !ok {
				return fmt.Errorf("stylefield %s: missing conv for %q", f.Name, name)
			}
		}
		fmt.Fprintf(&out, "%q:{kind:%q,convs:map[string]styleConversion{", f.Name, f.Kind)
		for _, name := range rendererOrder {
			c := byRenderer[name]
			if !parses[c.Parse] {
				return fmt.Errorf("stylefield %s/%s: undeclared parse token %q", f.Name, name, c.Parse)
			}
			if !posts[c.Post] {
				return fmt.Errorf("stylefield %s/%s: undeclared post token %q", f.Name, name, c.Post)
			}
			// A conversion with no citation is unverified. It must not claim a
			// modeled parse or post step, because that would read as evidence.
			if c.Cite == "" {
				if c.Verified != "" {
					return fmt.Errorf("stylefield %s/%s: verified scope without a citation", f.Name, name)
				}
				if c.Parse != "unmodeled" || c.Post != "unmodeled" {
					return fmt.Errorf("stylefield %s/%s: uncited conversion must be unmodeled", f.Name, name)
				}
			} else if c.Verified != name {
				return fmt.Errorf("stylefield %s/%s: citation requires verified=%q", f.Name, name, name)
			}
			fmt.Fprintf(&out, "%q:{parse:%q,post:%q,verified:%t,citation:%q},", name, c.Parse, c.Post, c.Verified == name, c.Cite)
		}
		fmt.Fprint(&out, "}},\n")
	}
	fmt.Fprintln(&out, "}")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}
	target := "style_matrix_generated.go"
	if *check {
		current, err := os.ReadFile(target)
		if err != nil {
			return err
		}
		if !bytes.Equal(canonicalNewlines(current), formatted) {
			return fmt.Errorf("%s is stale: run go generate ./internal/ass/renderer", target)
		}
		return nil
	}
	return os.WriteFile(target, formatted, 0644)
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
